def fact(sentence):
    """定稿就在这一层收敛：句子里只留事实。"""
    return (sentence or '').strip()


def subject(name):
    """正文里的对象名 —— 只在**多个对象并列**时才需要（如「6 个所」）。

    单个对象（本所 / 本市）不写自己是谁：他有账号，写出来是废话。
    """
    return (name or '').strip()
