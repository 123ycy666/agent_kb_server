# -*- coding: utf-8 -*-
"""名称归一·单位级别回归（2026-10-26）。

    python tests/test_name_level.py

为什么单独一个文件：`name_corrector` 里「选哪个标准名」的规则最容易改一个坏三个。
这里固定三类必须成立的行为：

  A. **用户明说了级别就按级别选**（2026-10-26 线上事故的根因）
     「广水公司」曾被判成「广水所」—— 因为 rank() 末位是「短名优先」，
     而「广水供电所」永远比「国网广水市供电公司」短。
  B. **用户写出来的后缀要吸收**，不能叠成「广水供电所公司」「广水供电所所」。
  C. **用户说的级别库里没有时不跨级别替换**（「广水服务站」库里没有 →
     保持原样，而不是拼出「广水供电所服务站」这种查不到的名字）。

另外把历史踩过的坑一并钉住（环谭/凉水/售电量和/广水所有…），防止修 A 破坏了它们。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.secretary import name_fix   # noqa: E402

# (输入, 期望输出, 说明)
CASES = [
    # A. 级别判定
    ('广水公司2026年预算', '国网广水市供电公司2026年预算', '公司级：短名不能赢'),
    ('广水供电公司预算执行', '国网广水市供电公司预算执行', '已写全称仍要归到标准名'),
    ('广水市供电公司预算', '国网广水市供电公司预算', '不能被企业台区「市供电公司箱变」吃掉'),
    # B. 后缀吸收
    ('广水所线损', '广水供电所线损', '不能变成「广水供电所所」'),
    # C. 库里没有该级别 → 不猜
    ('广水服务站线损', '广水服务站线损', '库里无「广水供电服务站」，不跨级别替换'),
    # 历史坑位
    ('环谭供电所的现损', '环潭供电所的线损', '同音错字 + 术语纠错'),
    ('凉水售电量', '两水供电所售电量', '裸地名归到单位名，且不吞指标名'),
    ('厉山供电所线损', '厉山供电所线损', '不能被改成「厉山供电所公变」'),
    ('售电量和线损', '售电量和线损', '「量和」同音于「两河」，不能当地名'),
    ('广水所有台区', '广水所有台区', '「所有」里的「所」不能被当后缀吃掉'),
    ('白鹤2组台区线损', '白鹤二组公变线损', '台区类型词替换（台区→公变）'),
    ('陈家河1#台区的线损率', '陈家河1#的线损率', '台区后缀可省，编号保留'),
]


def main() -> int:
    if not name_fix.status().get('available'):
        print('纠错词典不可用，无法测试：%s' % name_fix.status().get('reason'))
        return 1

    ok = fail = 0
    print('=' * 78)
    print('名称归一 · 单位级别回归')
    print('=' * 78)
    for src, want, why in CASES:
        got = (name_fix.fix(src).get('text') or '')
        if got == want:
            ok += 1
            print('  [ OK ] %-22s -> %s' % (src, got))
        else:
            fail += 1
            print('  [FAIL] %-22s -> %s' % (src, got))
            print('         期望 %-24s （%s）' % (want, why))
    print('\n' + '=' * 78)
    print('结果：%d 通过 / %d 失败' % (ok, fail))
    print('=' * 78)
    return 1 if fail else 0


if __name__ == '__main__':
    sys.exit(main())
